    private void btncheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncheckoutActionPerformed
        // TODO add your handling code here:
        String guestname = txtnamecheckout.getText().trim();
        String bookingref = txtrefcheckout.getText().trim();
        String roomnumber = txtroomcheckout.getText().trim();
        String day = daycheckout.getSelectedItem().toString();
        String month = monthcheckout.getSelectedItem().toString();
        String year = yearcheckout.getSelectedItem().toString();

        if (guestname.isEmpty()) {
            lblnamecheckouterror.setText("Guest name is required.");

        } else {
            lblnamecheckouterror.setText("");
        }
        if (bookingref.isEmpty()) {
            lblrefcheckouterror.setText("Booking reference is required.");
        } else {
            lblrefcheckouterror.setText("");
        }
        if (roomnumber.isEmpty()) {
            lblroomcheckouterror.setText("Room number is required.");
        } else {
            lblroomcheckouterror.setText("");
        }
        boolean validDate = true;

        String dayText = daycheckout.getSelectedItem().toString();
        String monthText = monthcheckout.getSelectedItem().toString();
        String yearText = yearcheckout.getSelectedItem().toString();

        if (dayText.equals("Select day")
            || monthText.equals("Select month")
            || yearText.equals("Select year")) {

            validDate = false;
            lbldatecheckouterror.setText("Please select a complete date.");

        } else {
            try {
                int selectedDay = Integer.parseInt(dayText);
                int selectedYear = Integer.parseInt(yearText);

                int selectedMonth = java.time.Month.valueOf(
                    monthText.toUpperCase()
                ).getValue();

                java.time.LocalDate.of(
                    selectedYear, selectedMonth, selectedDay
                );

                lbldatecheckouterror.setText("");

            } catch (java.time.DateTimeException
                | NumberFormatException ex) {

                validDate = false;
                lbldatecheckouterror.setText("Please select a valid date.");
            }
        }

        if(guestname.isEmpty() || bookingref.isEmpty() || roomnumber.isEmpty() || !validDate){
            return;
        }
        javax.swing.JOptionPane.showMessageDialog(null, "All check-in fields are complete!",
            "Validation Successful",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_btncheckoutActionPerformed

