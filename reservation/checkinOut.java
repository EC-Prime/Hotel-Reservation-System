    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String search = txtsearchreservation.getText().trim();

if (search.isEmpty() || search.equals(
        "Enter guest name, booking reference or room number...")) {

    lblerror.setText("Please enter a search value.");
    lblerror.setForeground(Color.RED);
    return;
}

boolean found = false;

for (int i = 0; i < tblreservationstatus.getRowCount(); i++) {

    String reference = String.valueOf(
            tblreservationstatus.getValueAt(i, 0));

    String guestName = String.valueOf(
            tblreservationstatus.getValueAt(i, 1));

    String roomNumber = String.valueOf(
          tblreservationstatus.getValueAt(i, 2));
    if (reference.equalsIgnoreCase(search)
            || guestName.toLowerCase().contains(search.toLowerCase())
            || roomNumber.equalsIgnoreCase(search)) {

        tblreservationstatus.setRowSelectionInterval(i, i);

        tblreservationstatus.scrollRectToVisible(
                tblreservationstatus.getCellRect(i, 0, true));

        lblerror.setText("Reservation found!");
        lblerror.setForeground(new Color(46, 204, 113));

        found = true;
        break;
    }
}

if (!found) {
    tblreservationstatus.clearSelection();
    lblerror.setText("No reservation found.");
    lblerror.setForeground(Color.RED);
}
    }//GEN-LAST:event_jButton1ActionPerformed

