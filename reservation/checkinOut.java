    private void btncheckinActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncheckinActionPerformed
            // TODO add your handling code here:
            String guestname = txtnamecheckin.getText().trim();
            String bookingref = txtrefcheckin.getText().trim();
            String roomnumber = txtroomcheckin.getText().trim();
            String day = daycheckin.getSelectedItem().toString();
            String month = monthcheckin.getSelectedItem().toString();
            String year = yearcheckin.getSelectedItem().toString();

            if (guestname.isEmpty()) {
                lblnamecheckinerror.setText("Guest name is required.");

            } else {
                lblnamecheckinerror.setText("");
            }
            if (bookingref.isEmpty()) {
                lblrefcheckinerror.setText("Booking reference is required.");
            } else {
                lblrefcheckinerror.setText("");
            }
            if (roomnumber.isEmpty()) {
                lblroomcheckinerror.setText("Room number is required.");
            } else {
                lblroomcheckinerror.setText("");
            }
          boolean validDate = true;

String dayText = daycheckin.getSelectedItem().toString();
String monthText = monthcheckin.getSelectedItem().toString();
String yearText = yearcheckin.getSelectedItem().toString();

if (dayText.equals("Select day")
        || monthText.equals("Select month")
        || yearText.equals("Select year")) {

    validDate = false;
    lbldatecheckinerror.setText("Please select a complete date.");

} else {
    try {
        int selectedDay = Integer.parseInt(dayText);
        int selectedYear = Integer.parseInt(yearText);

        int selectedMonth = java.time.Month.valueOf(
            monthText.toUpperCase()
        ).getValue();

        java.time.LocalDate.of(
            selectedYear, selectedMonth, selectedDay
        );

        lbldatecheckinerror.setText("");

    } catch (java.time.DateTimeException
            | NumberFormatException ex) {

        validDate = false;
        lbldatecheckinerror.setText("Please select a valid date.");
    }
}

    if(guestname.isEmpty() || bookingref.isEmpty() || roomnumber.isEmpty() || !validDate){
              return;
          }
          javax.swing.JOptionPane.showMessageDialog(null, "All check-in fields are complete!",
                  "Validation Successful",
                  javax.swing.JOptionPane.INFORMATION_MESSAGE);
        
    }//GEN-LAST:event_btncheckinActionPerformed

